"""
slice_fortress_sheet.py

Cuts "Fantasy Fortress Asset Sheet.png" into the block and garrison images the
game loads from assets/sprites/blocks/:

  block_dirt.png block_wood.png block_clay.png block_clay_cracked.png
  block_stone.png block_stone_cracked.png          104x72 (2x), full bleed
  garrison_tower.png garrison_keep.png garrison_tower_right.png
                                                    tower art, 2x, see below

  python3 tools/slice_fortress_sheet.py ["/path/to/sheet.png"]

Garrison images: the walkway (where the dwarf stands) is on row WALK_ROW and its
plank centre on the middle column. Steps can be up to 196 game px tall, taller
than the art, so each tower is extended downward by repeating its bottom
two-course brick band; the game clips everything below the floor. Also writes
src/actors/BlockSpriteMeta.ts with the label (banner) positions.

Requires Pillow, numpy.
"""

import json
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SHEET = ROOT.parent / 'Fantasy Fortress Asset Sheet.png'
OUT_DIR = ROOT / 'assets' / 'sprites' / 'blocks'
META_TS = ROOT / 'src' / 'actors' / 'BlockSpriteMeta.ts'

BLOCK_SIZE = (104, 72)
BLOCKS = [  # name, sheet bbox
    ('block_dirt', (16, 27, 245, 179)),
    ('block_wood', (268, 28, 497, 179)),
    ('block_clay', (527, 28, 752, 179)),
    ('block_clay_cracked', (782, 28, 1007, 179)),
    ('block_stone', (1038, 28, 1264, 179)),
    ('block_stone_cracked', (1293, 27, 1518, 179)),
]

WALKWAY_Y = 351           # sheet row of the walkway top (same on all three)
BRICK_PERIOD = 102        # sheet rows per two brick courses
WALK_ROW = 64             # stored row of the walkway
TOWER_HEIGHT = 480        # stored px; covers the tallest step (196 game px) with margin
# name: (sheet bbox, walkway plank x-span, stored plank width, label centre, sheet row the art is cut at)
# The keep is cut mid-portcullis so its extension repeats gate grid, not the spiked bottom.
TOWERS = {
    'garrison_tower': ((32, 214, 497, 1003), (160, 500), 148, (335, 655), 993),
    'garrison_keep': ((533, 225, 1005, 1003), (535, 1000), 154, (767, 612), 870),
    'garrison_tower_right': ((1040, 214, 1505, 1003), (1040, 1400), 148, (1195, 655), 993),
}


def clean_alpha(img: Image.Image) -> Image.Image:
    a = np.array(img)
    a[a[:, :, 3] < 60] = 0
    return Image.fromarray(a)


def main() -> None:
    sheet = clean_alpha(Image.open(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SHEET).convert('RGBA'))
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    for name, box in BLOCKS:
        sheet.crop(box).resize(BLOCK_SIZE, Image.LANCZOS).save(OUT_DIR / f'{name}.png', optimize=True)
        print(f'{name}.png')

    labels = {}
    for name, ((x0, y0, x1, y1), (px0, px1), plank_w, (lx, ly), cut_y) in TOWERS.items():
        scale = plank_w / (px1 - px0)
        plank_cx = (px0 + px1) / 2

        # Extend the art downward with whole brick bands taken from just above the cut
        art = sheet.crop((x0, y0, x1, cut_y))
        band = art.crop((0, art.height - BRICK_PERIOD, art.width, art.height))
        needed = (TOWER_HEIGHT - WALK_ROW) / scale + (WALKWAY_Y - y0)
        tall = Image.new('RGBA', (art.width, int(needed) + BRICK_PERIOD))
        tall.paste(art, (0, 0))
        y = art.height
        while y < tall.height:
            tall.paste(band, (0, y))
            y += BRICK_PERIOD

        scaled = tall.resize((round(tall.width * scale), round(tall.height * scale)), Image.LANCZOS)
        half = max(plank_cx - x0, x1 - plank_cx) * scale
        width = int(np.ceil(half)) * 2 + 4
        out = Image.new('RGBA', (width, TOWER_HEIGHT))
        ox = round(width / 2 - (plank_cx - x0) * scale)
        oy = round(WALK_ROW - (WALKWAY_Y - y0) * scale)
        out.alpha_composite(scaled.crop((0, max(-oy, 0), scaled.width, scaled.height)), (ox, max(oy, 0)))
        out = out.crop((0, 0, width, TOWER_HEIGHT))
        out.save(OUT_DIR / f'{name}.png', optimize=True)
        print(f'{name}.png ({width}x{TOWER_HEIGHT})')

        # Label centre relative to (plank centre, walkway top), game px
        labels[name] = [round((lx - plank_cx) * scale / 2, 1), round((ly - WALKWAY_Y) * scale / 2, 1)]

    META_TS.write_text(
        '/**\n'
        ' * BlockSpriteMeta.ts\n'
        ' * GENERATED by tools/slice_fortress_sheet.py - do not edit by hand.\n'
        ' * Garrison art layout: walkway row (stored px) and LOW/MID/HIGH label centres\n'
        ' * (game px from the walkway centre).\n'
        ' */\n\n'
        f'export const GARRISON_WALK_ROW = {WALK_ROW};\n'
        f'export const GARRISON_LABELS: Record<string, number[]> = {json.dumps(labels)};\n'
    )
    print(f'wrote {META_TS.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
